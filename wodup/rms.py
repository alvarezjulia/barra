#!/usr/bin/env python3
"""The athlete's RMs: generates data/barra.html, data/rms.json and data/rms.md.

barra.html works offline as a single file, so it cannot read data at runtime:
the PRs (data/athlete.json) and the implied RM from the history are baked in
between the ATHLETE START/END markers of a personal copy. The repo's
barra.html stays empty and generic.

Which number is picked, and why:

- **The one from the latest session**, not the all-time max: it is the RM the
  coach is programming against *now*.
- **The mode of the sets** (`impliedRM`), not the top set: on a ramp the
  heaviest set is a one-off attempt.
- **At least two sessions with a percentage**, so one odd day is not taken for
  a trend.
- **Exact names only, and only movements whose % is of their own 1RM.** The
  Romanian Deadlift is programmed at 50% *of the deadlift*: it gave a "RDL RM"
  of 130 kg and would have put 91 kg on the bar at 70%. Pulls, same thing. Just
  in case, any implied RM above MAX_OVER_PR × the PR is discarded.

The data folder defaults to <repo>/data and can be overridden with BARRA_DATA.
"""

from __future__ import annotations

import json
import os
import pathlib
import sys
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = pathlib.Path(os.environ.get("BARRA_DATA") or ROOT / "data")
BARRA = ROOT / "barra.html"

START = "// ===== ATHLETE START ====="
END = "// ===== ATHLETE END ====="

# WodUp name -> key in barra.html. Before adding one, check which RM it is
# programmed against.
WODUP_NAMES = {
    "Back Squat": "back_squat", "Front Squat": "front_squat", "Overhead Squat": "ohs",
    "Clean": "clean", "Power Clean": "power_clean", "Squat Clean": "squat_clean",
    "Clean and Jerk": "clean_jerk", "Snatch": "snatch", "Power Snatch": "power_snatch",
    "Squat Snatch": "squat_snatch", "Push Press": "push_press", "Push Jerk": "push_jerk",
    "Split Jerk": "split_jerk", "Jerk": "jerk", "Snatch Balance": "snatch_balance",
    "Thruster": "thruster", "Bench Press": "bench", "Strict Press": "strict_press",
    "Deadlift": "deadlift",
}
MIN_SESSIONS = 2
MAX_OVER_PR = 1.6


def series(days) -> dict[str, list[tuple[str, float, float | None]]]:
    """By movement name: [(date, implied RM, top RM)], in order."""
    out = defaultdict(list)
    for day in days:
        for b in day["blocks"]:
            name = (b["movement"] or {}).get("name")
            if name and b.get("impliedRM"):
                out[name].append((day["date"], b["impliedRM"], b.get("impliedRMTop")))
    return out


def hist_maxes(by_lift, seed):
    maxes, discarded = {}, []
    for name, hist in sorted(by_lift.items()):
        key = WODUP_NAMES.get(name)
        if not key:
            continue
        if len(hist) < MIN_SESSIONS:
            discarded.append(f"{key}: only {len(hist)} session with %")
            continue
        date, kg, _ = hist[-1]
        pr = seed.get(key)
        if pr and kg > pr * MAX_OVER_PR:
            discarded.append(f"{key}: {kg:g} kg is {kg / pr:.1f}× the PR ({pr:g}); the % was not of this movement")
            continue
        maxes[key] = {"kg": round(kg, 1), "date": date, "sessions": len(hist),
                      "recent": [round(h[1], 1) for h in hist[-3:]]}
    return maxes, discarded


def js_block(seed, maxes, days) -> str:
    js = lambda o: json.dumps(o, ensure_ascii=False, separators=(",", ":"))   # noqa: E731
    return "\n".join([
        START,
        "// Generated by wodup/rms.py: do not edit by hand.",
        "// WodUp PRs, and the implied RM of each movement's latest session",
        "// (kilos ÷ programmed %): the RM actually being programmed against.",
        f"// Based on {len(days)} training days, {days[0]['date']} → {days[-1]['date']}.",
        f"const SEED_MAXES = {js(seed)};",
        f"const HIST_MAXES = {js(maxes)};",
        END,
    ])


def wodup_prs() -> dict[str, tuple[float, str]]:
    """Best 1RM recorded in WodUp per movement: (kg, date)."""
    f = DATA / "prs-raw.json"
    if not f.exists():
        return {}
    best = {}
    for p in json.loads(f.read_text())["data"]["currentUser"]["strengthPrsForMovements"]:
        if p.get("reps") == 1 and p.get("load"):
            name = p["movement"]["name"]
            if name not in best or p["load"] > best[name][0]:
                best[name] = (p["load"], (p.get("result") or {}).get("doneOn"))
    return best


def report(by_lift, seed) -> str:
    """The three RM sources side by side: seeded, WodUp PR and implied."""
    prs = wodup_prs()
    g = lambda v: f"{v:g}" if v else "—"   # noqa: E731
    out = ["# RMs: seeded vs actual", "",
           "**Last implied RM** is what drives the calculation: the RM the latest session was programmed with.", "",
           "| Movement | `barra.html` | WodUp PR | Last implied RM | Last top | Max implied RM | Sessions w/ % |",
           "|---|---|---|---|---|---|---|"]
    by_key = {v: k for k, v in WODUP_NAMES.items()}
    for key, seeded in sorted(seed.items(), key=lambda kv: by_key.get(kv[0], kv[0])):
        name = by_key.get(key, key)
        hist = by_lift.get(name, [])
        pr = prs.get(name)
        out.append("| {} | {:g} | {} | {} | {} | {} | {} |".format(
            name, seeded, f"{pr[0]:g} ({pr[1]})" if pr else "—",
            f"{hist[-1][1]:g} ({hist[-1][0]})" if hist else "—",
            g(hist[-1][2]) if hist else "—", g(max(h[1] for h in hist)) if hist else "—",
            len(hist) or "—"))
    out += ["", "## Movements with % that are not in `barra.html`", "",
            "| Movement | Sessions w/ % | Last implied RM | Max implied RM |", "|---|---|---|---|"]
    for name, hist in sorted(by_lift.items(), key=lambda kv: -len(kv[1])):
        if name not in WODUP_NAMES and len(hist) >= 3:
            out.append(f"| {name} | {len(hist)} | {hist[-1][1]:g} ({hist[-1][0]}) | {max(h[1] for h in hist):g} |")
    return "\n".join(out) + "\n"


def main():
    if not (DATA / "athlete.json").exists():
        sys.exit("Missing data/athlete.json. Start with:  make data")
    if not (DATA / "history.json").exists():
        sys.exit("Missing data/history.json. Download it from WodUp with:  make web")
    athlete = json.loads((DATA / "athlete.json").read_text())
    seed = athlete["prs"]
    days = json.loads((DATA / "history.json").read_text())["days"]
    html = BARRA.read_text()
    a, b = html.find(START), html.find(END)
    if a < 0 or b < 0:
        sys.exit("Cannot find the ATHLETE START/END markers in barra.html")

    by_lift = series(days)
    maxes, discarded = hist_maxes(by_lift, seed)
    (DATA / "barra.html").write_text(html[:a] + js_block(seed, maxes, days) + html[b + len(END):])
    (DATA / "rms.json").write_text(json.dumps({"SEED_MAXES": seed, "HIST_MAXES": maxes}, indent=1))
    (DATA / "rms.md").write_text(report(by_lift, seed))

    print(f"{len(maxes)} RMs in data/barra.html: " +
          ", ".join(f"{k} {v['kg']:g}" for k, v in sorted(maxes.items())))
    for d in discarded:
        print(f"  discarded {d}")


if __name__ == "__main__":
    main()
